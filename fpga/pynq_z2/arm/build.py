"""Build a bare-metal Cortex-A9 program for the Zynq PS with the Arm GNU toolchain
(arm-none-eabi-gcc), no BSP: start.S, uart.c and the program's own .c files, linked into OCM.

    python fpga/pynq_z2/arm/build.py test_regs [more.c ...] [--asm <program.asm>:<name> ...]

Writes build/pynq_z2_axi/arm/<name>.elf and prints the address of its `result` symbol,
which run_arm.tcl reads back over JTAG. Each --asm assembles a SmallCore program with
model/cpu.py into gen/<name>.h, `static const uint16_t <name>[]` and `<name>_words`, for
sc_load_ram().
"""

import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
OUT = ROOT / "build" / "pynq_z2_axi" / "arm"
FLAGS = ["-mcpu=cortex-a9", "-marm", "-mfloat-abi=soft", "-O2", "-g", "-Wall", "-Wextra",
         "-ffreestanding", "-nostdlib", "-nostartfiles", "-fno-builtin", "-mno-unaligned-access",
         "-Wl,--no-warn-rwx-segments"]


def tool(name):
    found = shutil.which(name)
    if found:
        return found
    for d in sorted(Path("C:/Program Files (x86)/Arm GNU Toolchain arm-none-eabi").glob("*/bin")):
        if (d / (name + ".exe")).exists():
            return str(d / (name + ".exe"))
    raise SystemExit(f"{name} not found: install the Arm GNU toolchain or put it on PATH")


def gen_program(spec):
    path, _, var = spec.partition(":")
    sys.path.insert(0, str(ROOT / "model"))
    from cpu import assemble
    words = assemble((ROOT / path).read_text())
    body = ",\n".join("    " + ", ".join(f"0x{w:04X}" for w in words[i:i + 8]) for i in range(0, len(words), 8))
    (OUT / "gen").mkdir(parents=True, exist_ok=True)
    (OUT / "gen" / f"{var}.h").write_text(
        f"/* {path}, assembled by model/cpu.py: {len(words)} words. Generated by build.py. */\n"
        f"static const uint16_t {var}[] = {{\n{body}\n}};\n"
        f"#define {var}_words {len(words)}u\n")


def build(name, extra, programs):
    OUT.mkdir(parents=True, exist_ok=True)
    for p in programs:
        gen_program(p)
    srcs = [HERE / "start.S", HERE / "uart.c", HERE / f"{name}.c"] + [HERE / e for e in extra]
    elf = OUT / f"{name}.elf"
    subprocess.run([tool("arm-none-eabi-gcc")] + FLAGS + ["-I", str(OUT / "gen"), "-T", str(HERE / "link.ld"),
                    "-o", str(elf)] + [str(s) for s in srcs] + ["-lgcc"], check=True)
    syms = subprocess.run([tool("arm-none-eabi-nm"), str(elf)], check=True, capture_output=True, text=True).stdout
    result = next((l.split()[0] for l in syms.splitlines() if l.split()[-1] == "result"), None)
    exc = next((l.split()[0] for l in syms.splitlines() if l.split()[-1] == "exception_seen"), None)
    size = subprocess.run([tool("arm-none-eabi-size"), str(elf)], check=True, capture_output=True, text=True).stdout
    print(size.strip())
    print(f"ELF {elf}")
    print(f"RESULT_ADDR 0x{result}" if result else "RESULT_ADDR none")
    print(f"EXCEPTION_ADDR 0x{exc}" if exc else "EXCEPTION_ADDR none")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    args = sys.argv[2:]
    programs = [args[i + 1] for i, a in enumerate(args) if a == "--asm"]
    extra = [a for i, a in enumerate(args) if a != "--asm" and (i == 0 or args[i - 1] != "--asm")]
    build(sys.argv[1], extra, programs)
